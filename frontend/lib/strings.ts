export type Lang = "hi" | "en";
export type StringKey = Key;
export const strings: Record<Lang, Record<Key, string>> = { en, hi };

const REJECTION_REASONS: Record<string, Key> = {
  promise_date_past: "reasonPromiseDatePast",
  promise_date_too_far: "reasonPromiseDateTooFar",
  logged_in_future: "reasonLoggedInFuture",
  loan_not_found: "reasonLoanNotFound",
};

/** Why the server did not accept an outcome, as a dictionary key. */
export function rejectionReason(code: string | null | undefined): Key {
  return REJECTION_REASONS[code ?? ""] ?? "reasonCheck";
}

export function formatTime(iso: string, lang: Lang): string {
  const locale = lang === "hi" ? "hi-IN-u-nu-latn" : "en-IN";
  return new Date(iso).toLocaleTimeString(locale, { timeZone: "Asia/Kolkata", hour: "numeric", minute: "2-digit" });
}

